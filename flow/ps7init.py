import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

CONFIG = {
    "root": Path(__file__).resolve().parent.parent,
    "uboot": "upstream/u-boot_u-boot",
    "header": "arch/arm/mach-zynq/include/mach/ps7_init_gpl.h",
    "opcodes": {"MASKWRITE": (0, 3), "MASKPOLL": (1, 2), "MASKDELAY": (2, 2), "WRITE": (3, 2)},
    "poll_ms": 1000,
    "openocd": "toolchain/oss-cad-suite/bin/openocd",
    "cc": "gcc",
}

TABLE_RE = re.compile(r"static\s+unsigned\s+long\s+(\w+)\[\]\s*=\s*\{(.*?)\};", re.S)
EMIT_RE = re.compile(r"EMIT_(\w+)\(([^)]*)\)")
CALL_RE = re.compile(r"ps7_config\((\w+)\)")
FUNC_RE = re.compile(r"^int\s+(ps7_init|ps7_post_config)\s*\(void\)\s*\{(.*?)^\}", re.S | re.M)


def num(s):
    return int(s.strip().rstrip("uUlL"), 0)


def parse(path):
    text = Path(path).read_text()
    tables = {}
    for name, body in TABLE_RE.findall(text):
        ops = []
        for op, args in EMIT_RE.findall(body):
            vals = [num(a) for a in args.split(",") if a.strip()]
            if op == "EXIT":
                break
            if op not in CONFIG["opcodes"] or len(vals) != CONFIG["opcodes"][op][1]:
                raise ValueError(f"{path}: {name}: unknown or malformed EMIT_{op}({args})")
            ops.append([op] + vals)
        tables[name] = ops
    funcs = {f: CALL_RE.findall(body) for f, body in FUNC_RE.findall(text)}
    for f in ("ps7_init", "ps7_post_config"):
        if f not in funcs:
            raise ValueError(f"{path}: no {f}()")
        missing = [t for t in funcs[f] if t not in tables]
        if missing:
            raise ValueError(f"{path}: {f}() uses unknown tables {missing}")
    return {"tables": tables, "funcs": funcs}


def words(ops):
    out = []
    for op in ops:
        code = CONFIG["opcodes"][op[0]][0]
        out += [op[1] | code] + op[2:]
    return out + [0]


def tcl(ps, source):
    lines = [f"# OpenOCD Tcl generated by flow/ps7init.py from {source}",
             "# ps7_init / ps7_post_config: the same register sequence as U-Boot SPL's ps7_config() tables.",
             "# Run with the Cortex-A9 halted: halt; ps7_init; (load the PL); ps7_post_config",
             "proc ps7_read {addr} { return [lindex [read_memory $addr 32 1] 0] }",
             "proc ps7_write {addr val} { write_memory $addr 32 [list [expr {$val & 0xffffffff}]] }",
             "proc ps7_maskwrite {addr mask val} {",
             "    ps7_write $addr [expr {([ps7_read $addr] & ~$mask) | ($val & $mask)}]",
             "}",
             "proc ps7_maskpoll {addr mask} {",
             f"    for {{set i 0}} {{$i < {CONFIG['poll_ms']}}} {{incr i}} {{",
             "        if {[ps7_read $addr] & $mask} { return }",
             "        sleep 1",
             "    }",
             "    error [format \"ps7_init: poll 0x%08x mask 0x%08x timed out\" $addr $mask]",
             "}",
             "proc ps7_maskdelay {addr ms} { sleep $ms }"]
    for name, ops in ps["tables"].items():
        lines.append(f"proc {name} {{}} {{")
        for op in ops:
            args = " ".join(f"0x{v:08x}" if i == 0 or op[0] != "MASKDELAY" else str(v) for i, v in enumerate(op[1:]))
            lines.append(f"    ps7_{op[0].lower()} {args}")
        lines.append("}")
    for f in ("ps7_init", "ps7_post_config"):
        lines.append(f"proc {f} {{}} {{")
        lines += [f"    {t}" for t in ps["funcs"][f]]
        lines.append("}")
    return "\n".join(lines) + "\n"


MOCK_C = r"""
#include <stdio.h>
#include <asm/arch/ps7_init_gpl.h>
static unsigned long regs_a[4096], regs_v[4096];
static int nregs;
static const unsigned long polled[] = {POLLED 0};
static unsigned long rd(unsigned long a)
{
	for (int i = 0; polled[i]; i++)
		if (polled[i] == a)
			return 0xffffffffUL;
	for (int i = 0; i < nregs; i++)
		if (regs_a[i] == a)
			return regs_v[i];
	return 0;
}
static void wr(unsigned long a, unsigned long v)
{
	v &= 0xffffffffUL;
	printf("W %08lx %08lx\n", a, v);
	for (int i = 0; i < nregs; i++)
		if (regs_a[i] == a) {
			regs_v[i] = v;
			return;
		}
	regs_a[nregs] = a;
	regs_v[nregs++] = v;
}
int ps7_config(unsigned long *p)
{
	for (;;) {
		unsigned long op = p[0], a = op & OPCODE_ADDRESS_MASK;
		if (op == OPCODE_EXIT)
			return PS7_INIT_SUCCESS;
		switch (op & ~OPCODE_ADDRESS_MASK) {
		case OPCODE_MASKWRITE:
			wr(a, (rd(a) & ~p[1]) | (p[2] & p[1]));
			p += 3;
			break;
		case OPCODE_WRITE:
			wr(a, p[1]);
			p += 2;
			break;
		case OPCODE_MASKPOLL:
			printf("P %08lx %08lx\n", a, p[1]);
			if (!(rd(a) & p[1]))
				return PS7_INIT_TIMEOUT;
			p += 2;
			break;
		case OPCODE_MASKDELAY:
			printf("D %08lx %lu\n", a, p[1]);
			p += 2;
			break;
		default:
			return PS7_INIT_CORRUPT;
		}
	}
}
int main(void)
{
	printf("I %d\n", ps7_init());
	printf("O %d\n", ps7_post_config());
	return 0;
}
"""

MOCK_TCL = r"""
set ::regs [dict create]
set ::polled [list POLLED]
set ::log {}
proc read_memory {addr width count} {
    if {[lsearch -exact $::polled [format 0x%08x $addr]] >= 0} { return [list 0xffffffff] }
    if {[dict exists $::regs $addr]} { return [list [dict get $::regs $addr]] }
    return [list 0]
}
proc write_memory {addr width data} {
    set v [expr {[lindex $data 0] & 0xffffffff}]
    dict set ::regs $addr $v
    lappend ::log [format "W %08x %08x" $addr $v]
}
proc sleep {ms} { lappend ::log "S $ms" }
source GEN
ps7_init
lappend ::log "I 0"
ps7_post_config
lappend ::log "O 0"
set f [open OUT w]
puts $f [join $::log "\n"]
close $f
shutdown
"""


def selftest(c_file, tcl_file, work):
    root = CONFIG["root"]
    work = Path(work)
    work.mkdir(parents=True, exist_ok=True)
    ps = parse(c_file)
    polled = sorted({op[1] for ops in ps["tables"].values() for op in ops if op[0] == "MASKPOLL"})
    inc = work / "inc" / "asm" / "arch"
    inc.mkdir(parents=True, exist_ok=True)
    shutil.copy(root / CONFIG["uboot"] / CONFIG["header"], inc / "ps7_init_gpl.h")
    (work / "mock.c").write_text(MOCK_C.replace("POLLED", "".join(f"0x{a:08x}UL, " for a in polled)))
    exe = work / "ps7_ref"
    subprocess.run([CONFIG["cc"], "-O1", "-w", "-I", str(work / "inc"), "-o", str(exe), str(c_file), str(work / "mock.c")],
                   check=True)
    ref = subprocess.run([str(exe)], check=True, capture_output=True, text=True).stdout.split("\n")
    ref_w = [l for l in ref if l and l[0] in "WIO"]
    tcl_out = work / "tcl.log"
    (work / "mock.tcl").write_text(MOCK_TCL.replace("POLLED", " ".join(f"0x{a:08x}" for a in polled))
                                   .replace("GEN", str(Path(tcl_file).resolve())).replace("OUT", str(tcl_out)))
    r = subprocess.run([str(root / CONFIG["openocd"]), "-f", str(work / "mock.tcl")], capture_output=True, text=True)
    if not tcl_out.exists():
        print(r.stdout + r.stderr)
        return {"ok": False, "why": "openocd did not run the generated Tcl"}
    got = tcl_out.read_text().split("\n")
    got_w = [l for l in got if l and l[0] in "WIO"]
    first = next((i for i, (x, y) in enumerate(zip(ref_w, got_w)) if x != y), None)
    ok = ref_w == got_w and "I 0" in ref_w and ref_w[-1] == "O 0"
    n_ops = sum(len(v) for v in ps["tables"].values())
    return {"ok": ok, "ops": n_ops, "writes_c": len(ref_w) - 2, "writes_tcl": len(got_w) - 2,
            "polls_c": sum(1 for l in ref if l.startswith("P")), "delays_c": sum(1 for l in ref if l.startswith("D")),
            "sleeps_tcl": sum(1 for l in got if l.startswith("S")), "first_diff": first,
            "table_words": {k: len(words(v)) for k, v in ps["tables"].items()}}


def main():
    ap = argparse.ArgumentParser(description="ps7_init_gpl.c (U-Boot, GPL-2.0+) to an OpenOCD Tcl ps7_init for JTAG boot")
    ap.add_argument("c_file")
    ap.add_argument("out", help="Tcl file to write")
    ap.add_argument("--selftest", metavar="DIR", help="also check the Tcl against the C tables (host gcc + OpenOCD)")
    a = ap.parse_args()
    ps = parse(a.c_file)
    Path(a.out).write_text(tcl(ps, a.c_file))
    print(f"wrote {a.out}: {sum(len(v) for v in ps['tables'].values())} ops in {len(ps['tables'])} tables")
    if a.selftest:
        r = selftest(a.c_file, a.out, a.selftest)
        print(json.dumps(r))
        sys.exit(0 if r["ok"] else 1)


if __name__ == "__main__":
    main()
