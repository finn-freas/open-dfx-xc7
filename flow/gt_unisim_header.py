import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gt_json_defaults as G



def main():
    out = Path(sys.argv[1])
    src = Path(sys.argv[2] if len(sys.argv) > 2 else G.CONFIG["cells"]).read_text()
    lines = ["// Generated by open-dfx-xc7 flow/gt_unisim_header.py from yosys techlibs/xilinx/cells_xtra.v.",
             "// UNISIM default of every GTPE2_CHANNEL, GTPE2_COMMON and PCIE_2_1 parameter, in yosys' JSON",
             "// encoding (Property::from_string).",
             "#ifndef XILINX_GT_UNISIM_DEFAULTS_H", "#define XILINX_GT_UNISIM_DEFAULTS_H", "",
             "#include \"nextpnr_namespaces.h\"", "", "NEXTPNR_NAMESPACE_BEGIN", "",
             "struct GtUnisimDefault", "{", "    const char *prim;", "    const char *name;", "    const char *value;",
             "};", "", "static const GtUnisimDefault gt_unisim_defaults[] = {"]
    n = 0
    for prim in G.CONFIG["prims"]:
        for name, val in G.defaults(prim, src).items():
            lines.append(f'        {{"{prim}", "{name}", "{val}"}},')
            n += 1
    lines += ["};", "", "NEXTPNR_NAMESPACE_END", "", "#endif", ""]
    out.write_text("\n".join(lines))
    print(f"{out}: {n} defaults")


if __name__ == "__main__":
    main()
