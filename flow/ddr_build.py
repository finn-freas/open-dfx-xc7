import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gap_build
from gap_build import build

ROOT = gap_build.ROOT
LX = ROOT / "toolchain" / "litex"

CONFIG = {
    "dry_run": True,
    "python": LX / "venv" / "bin" / "python3",
    "path_prepend": [LX / "venv" / "bin", LX / "riscv" / "usr" / "bin"],
    "target": "litex_boards.targets.digilent_arty",
    "migen_sha1": "4c2ae8dfeea37f235b52acb8166f12acaaae4f7c",
    "top": "digilent_arty",
    "designs": {
        "arty_ddr3": ["--variant", "a7-35", "--sys-clk-freq", "100e6"],
        "arty_ddr3_s80": ["--variant", "a7-35", "--sys-clk-freq", "80e6"],
    },
    "gen_dir": ROOT / "build" / "ddr3" / "gen",
    "src_dir": ROOT / "designs" / "ddr3",
    "out_dir": ROOT / "build" / "ddr3",
    "vexriscv_v": LX / "src" / "pythondata-cpu-vexriscv" / "pythondata_cpu_vexriscv" / "verilog",
    "gate_max_nextpnr": 2,
    "gate_busy": ["make", "ninja"],
    "gate_poll_s": 30,
    "variants": {
        "gapfix": {"nextpnr": "build/nextpnr-build/gapfix/nextpnr-himbaechel",
                   "chipdb": "toolchain/openxc7/share/nextpnr/himbaechel/xilinx/chipdb-xc7a50t.bin",
                   "yosys_plugin": "build/yosys-plugin/clkbufmap_gapfix.so", "clkbuf_pass": "clkbufmap_gapfix",
                   "npr_args": ["--timing-allow-fail"]},
        "qorfix": {"nextpnr": "build/nextpnr-build/qorfix/nextpnr-himbaechel",
                   "chipdb": "toolchain/openxc7/share/nextpnr/himbaechel/xilinx/chipdb-xc7a50t.bin",
                   "yosys_plugin": "build/yosys-plugin/clkbufmap_gapfix.so", "clkbuf_pass": "clkbufmap_gapfix",
                   "npr_args": ["--timing-allow-fail", "-o", "hardblock-timing"]},
        "stock": {"nextpnr": None, "chipdb": None, "yosys_plugin": None, "clkbuf_pass": None,
                  "npr_args": ["--timing-allow-fail"]},
    },
    "xdc_drop": re.compile(r"^\s*(set_false_path|set_max_delay|set_clock_groups|set_property\s+INTERNAL_VREF)\b"),
    "freq_mhz": 100,
}


def env():
    e = dict(os.environ)
    e["PATH"] = ":".join(str(p) for p in CONFIG["path_prepend"]) + ":" + e["PATH"]
    return e


def busy():
    n = subprocess.run(["pgrep", "-c", "nextpnr"], capture_output=True, text=True).stdout.strip() or "0"
    if int(n) >= CONFIG["gate_max_nextpnr"]:
        return f"{n} nextpnr"
    for p in CONFIG["gate_busy"]:
        if subprocess.run(["pgrep", "-x", p], capture_output=True).returncode == 0:
            return p
    return None


def wait_gate():
    while (why := busy()):
        print(f"[wait] {why} running", flush=True)
        time.sleep(CONFIG["gate_poll_s"])


def generate(name, args, dry):
    out = CONFIG["gen_dir"] / name
    v = out / "gateware" / f"{CONFIG['top']}.v"
    if v.exists():
        print(f"[skip] gen {name}: {v.relative_to(ROOT)} exists")
        return out
    head = subprocess.run(["git", "-C", str(LX / "src" / "migen"), "rev-parse", "HEAD"], capture_output=True,
                          text=True).stdout.strip()
    if head != CONFIG["migen_sha1"]:
        sys.exit(f"migen is at {head}, LiteX pins {CONFIG['migen_sha1']} (litex/litex_repos.py)")
    cmd = [str(CONFIG["python"]), "-m", CONFIG["target"], "--toolchain", "vivado", *args,
           "--output-dir", str(out), "--build", "--no-compile-gateware"]
    print(f"[{'dry' if dry else 'run'}] gen {name}: {' '.join(cmd)}")
    if dry:
        return out
    out.mkdir(parents=True, exist_ok=True)
    with open(CONFIG["out_dir"] / f"gen_{name}.log", "w") as f:
        r = subprocess.run(cmd, stdout=f, stderr=subprocess.STDOUT, env=env(), cwd=ROOT)
    if r.returncode or not v.exists():
        sys.exit(f"gen {name} failed, see build/ddr3/gen_{name}.log")
    return out


def stage(name, gen, dry):
    src = CONFIG["src_dir"] / name
    gw = gen / "gateware"
    top = CONFIG["top"]
    if dry and not (gw / f"{top}.v").exists():
        print(f"[dry] stage {name} -> {src.relative_to(ROOT)}")
        return src
    src.mkdir(parents=True, exist_ok=True)
    (src / "nextpnr").mkdir(exist_ok=True)
    rtl = gw / f"{top}.v"
    cpus = re.findall(r'read_verilog \{([^}]*VexRiscv[^}]*\.v)\}', (gw / f"{top}.tcl").read_text())
    for p in [rtl, *map(Path, cpus), *gw.glob("*.init")]:
        shutil.copy2(p, src / p.name)
    shutil.copy2(gw / f"{top}.xdc", src / f"{top}.xdc")
    (src / "top.txt").write_text(top + "\n")
    keep = [ln for ln in (gw / f"{top}.xdc").read_text().splitlines() if not CONFIG["xdc_drop"].match(ln)]
    (src / "nextpnr" / f"{top}.xdc").write_text("\n".join(keep) + "\n")
    (src / "SOURCE.txt").write_text(
        f"generated by flow/ddr_build.py from {gen.relative_to(ROOT)}\n"
        f"command: python3 -m {CONFIG['target']} --toolchain vivado {' '.join(CONFIG['designs'][name])} --build --no-compile-gateware\n"
        f"litex commits: toolchain/litex/COMMITS.txt\n"
        f"{top}.xdc: LiteX's Vivado XDC, used by Vivado\n"
        f"nextpnr/{top}.xdc: same file without the lines nextpnr cannot use ({CONFIG['xdc_drop'].pattern})\n")
    return src


def pnr(name, src, variant, dry):
    v = CONFIG["variants"][variant]
    top = CONFIG["top"]
    absp = lambda p: str(ROOT / p) if p else None
    nextpnr = absp(v["nextpnr"])
    if not dry:
        wait_gate()
    tools = {"nextpnr": nextpnr, "chipdb": absp(v["chipdb"]), "yosys_plugin": absp(v["yosys_plugin"]),
             "clkbuf_pass": v["clkbuf_pass"]}
    rtl = [src / f"{top}.v", *sorted(p for p in src.glob("*.v") if p.name != f"{top}.v")]
    out = CONFIG["out_dir"] / name / variant
    return build(name, src, top, rtl, src / "nextpnr" / f"{top}.xdc", out, CONFIG["freq_mhz"], dry,
                 v["npr_args"], tools)


def main():
    ap = argparse.ArgumentParser(description="LiteX/LiteDRAM DDR3 SoC for the Arty A7-35T through the open flow")
    ap.add_argument("designs", nargs="*", default=list(CONFIG["designs"]))
    ap.add_argument("--variant", action="append", help=f"one of {list(CONFIG['variants'])} (default gapfix)")
    ap.add_argument("--gen-only", action="store_true")
    ap.add_argument("--run", action="store_true")
    a = ap.parse_args()
    dry = CONFIG["dry_run"] and not a.run
    CONFIG["out_dir"].mkdir(parents=True, exist_ok=True)
    for name in a.designs:
        gen = generate(name, CONFIG["designs"][name], dry)
        src = stage(name, gen, dry)
        if a.gen_only:
            continue
        for variant in a.variant or ["gapfix"]:
            rec = pnr(name, src, variant, dry)
            if not dry:
                print(json.dumps({k: {kk: vv for kk, vv in s.items() if kk in ("ok", "seconds", "error")}
                                  for k, s in rec["stages"].items()}, indent=1))


if __name__ == "__main__":
    main()
