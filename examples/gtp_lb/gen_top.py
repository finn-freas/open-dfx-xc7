MANUAL = {
    "GTPE2_COMMON": {"PLL0_FBDIV": "4", "PLL0_FBDIV_45": "5", "PLL0_REFCLK_DIV": "1"},
    "GTPE2_CHANNEL": {"RXOUT_DIV": "2", "TXOUT_DIV": "2", "RX_DATA_WIDTH": "20", "TX_DATA_WIDTH": "20",
                      "RX_CLK25_DIV": "5", "TX_CLK25_DIV": "5"},
}


def main():
    if sys.argv[1] == "manual":
        out, module = Path(sys.argv[2]), sys.argv[3]
        ch, co = dict(MANUAL["GTPE2_CHANNEL"]), dict(MANUAL["GTPE2_COMMON"])
    else:
        wiz = Path(sys.argv[1])
        out, module = CONFIG["out"], "gtp_lb"
        ch_text = (wiz / CONFIG["channel_src"]).read_text()
        co_text = (wiz / CONFIG["common_src"]).read_text()
        ch = resolve(inst_params(ch_text, "GTPE2_CHANNEL"), module_params(ch_text))
        co = resolve(inst_params(co_text, "GTPE2_COMMON"), module_params(co_text))
    CONFIG["out"] = out
    chparams, chmiss = plist("GTPE2_CHANNEL", ch)
    cparams, cmiss = plist("GTPE2_COMMON", co)
    CONFIG["out"].parent.mkdir(parents=True, exist_ok=True)
    text = TOP.format(cparams=cparams, chparams=chparams, cmiss=" ".join(cmiss) or "none",
                      chmiss=" ".join(chmiss) or "none")
    if module != "gtp_lb":
        text = text.replace("module gtp_lb (", f"module {module} (").replace(
            "from the Vivado 7 Series Transceivers Wizard sources", "with only the rate attributes set (gen_top.py MANUAL)")
    CONFIG["out"].write_text(text)
    print(f"wrote {CONFIG['out']}: channel {len(ch)} wizard attributes, {len(chmiss)} defaults; "
          f"common {len(co)} wizard attributes, {len(cmiss)} defaults")
    unresolved = [f"{n}={v}" for n, v in list(ch.items()) + list(co.items()) if re.fullmatch(r"[A-Za-z_]\w*", v)]
    if unresolved:
        print("unresolved:", " ".join(unresolved))


if __name__ == "__main__":
    main()
