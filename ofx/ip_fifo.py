"""ofx ip fifo: FIFO Generator equivalent.

Implementations (Vivado's names): Common_Clock_Block_RAM, Common_Clock_Distributed_RAM,
Independent_Clocks_Block_RAM, Independent_Clocks_Distributed_RAM (fabric RTL, inferred RAMB or LUTRAM), and
Common_Clock_Builtin_FIFO / Independent_Clocks_Builtin_FIFO (FIFO18E1/FIFO36E1 primitives).
Read modes: Standard_FIFO, First_Word_Fall_Through. Optional flags: almost_full/empty, valid, overflow,
underflow, prog_full/prog_empty (single constant thresholds), data_count / wr_data_count / rd_data_count.
Port names follow fifo_generator so a design can swap the two. The cycle behaviour of the fabric FIFOs is checked
against Vivado's fifo_generator_v13_2 behavioural model (flow/ip_compare.py fifo).
"""
import math

CONFIG = {
    "impls": ("Common_Clock_Block_RAM", "Common_Clock_Distributed_RAM", "Independent_Clocks_Block_RAM",
              "Independent_Clocks_Distributed_RAM", "Common_Clock_Builtin_FIFO", "Independent_Clocks_Builtin_FIFO"),
    "sync_stages": 2,
    "fifo36": [(4, 8192), (9, 4096), (18, 2048), (36, 1024), (72, 512)],
    "fifo18": [(4, 4096), (9, 2048), (18, 1024), (36, 512)],
}


class FifoError(Exception):
    pass


def options(p):
    """Vivado-style property dict -> normalized options."""
    impl = p.get("Fifo_Implementation", "Common_Clock_Block_RAM")
    if impl not in CONFIG["impls"]:
        raise FifoError(f"Fifo_Implementation {impl}: one of {CONFIG['impls']}")
    t = lambda k: str(p.get(k, "false")).lower() == "true"
    o = {"impl": impl, "fwft": p.get("Performance_Options", "Standard_FIFO") == "First_Word_Fall_Through",
         "width": int(p.get("Input_Data_Width", 18)), "depth": int(p.get("Input_Depth", 1024)),
         "common": impl.startswith("Common"), "builtin": impl.endswith("Builtin_FIFO"),
         "ram": "distributed" if "Distributed" in impl else "block",
         "almost_full": t("Almost_Full_Flag"), "almost_empty": t("Almost_Empty_Flag"), "valid": t("Valid_Flag"),
         "overflow": t("Overflow_Flag"), "underflow": t("Underflow_Flag"), "data_count": t("Data_Count"),
         "wr_data_count": t("Write_Data_Count"), "rd_data_count": t("Read_Data_Count"),
         "prog_full": int(p["Full_Threshold_Assert_Value"]) if "Programmable_Full_Type" in p and
         p["Programmable_Full_Type"] != "No_Programmable_Full_Threshold" else None,
         "prog_empty": int(p["Empty_Threshold_Assert_Value"]) if "Programmable_Empty_Type" in p and
         p["Programmable_Empty_Type"] != "No_Programmable_Empty_Threshold" else None}
    if o["depth"] & (o["depth"] - 1) or o["depth"] < 16:
        raise FifoError(f"depth {o['depth']}: a power of two >= 16")
    for k in ("data_count_width", "wr_data_count_width", "rd_data_count_width"):
        vk = {"data_count_width": "Data_Count_Width", "wr_data_count_width": "Write_Data_Count_Width",
              "rd_data_count_width": "Read_Data_Count_Width"}[k]
        o[k] = int(p.get(vk, int(math.log2(o["depth"]))))
    return o


def ports(o):
    pl = []
    if o["common"]:
        pl += [("input", "clk", 1), ("input", "srst", 1)]
    else:
        pl += [("input", "rst", 1), ("input", "wr_clk", 1), ("input", "rd_clk", 1)]
    pl += [("input", "din", o["width"]), ("input", "wr_en", 1), ("input", "rd_en", 1), ("output", "dout", o["width"]),
           ("output", "full", 1)]
    if o["almost_full"]:
        pl.append(("output", "almost_full", 1))
    if o["overflow"]:
        pl.append(("output", "overflow", 1))
    pl.append(("output", "empty", 1))
    if o["almost_empty"]:
        pl.append(("output", "almost_empty", 1))
    if o["valid"]:
        pl.append(("output", "valid", 1))
    if o["underflow"]:
        pl.append(("output", "underflow", 1))
    if o["data_count"]:
        pl.append(("output", "data_count", o["data_count_width"]))
    if o["rd_data_count"]:
        pl.append(("output", "rd_data_count", o["rd_data_count_width"]))
    if o["wr_data_count"]:
        pl.append(("output", "wr_data_count", o["wr_data_count_width"]))
    if o["prog_full"] is not None:
        pl.append(("output", "prog_full", 1))
    if o["prog_empty"] is not None:
        pl.append(("output", "prog_empty", 1))
    if not o["common"] or o["builtin"]:
        pl += [("output", "wr_rst_busy", 1), ("output", "rd_rst_busy", 1)]
    return pl


def header(name, o, pl):
    return [f"// generated by ofx ip fifo: {o['impl']} {'FWFT' if o['fwft'] else 'standard'} {o['width']}x{o['depth']}",
            f"module {name} (\n" + ",\n".join(f"    {d} wire{f' [{w - 1}:0]' if w > 1 else ''} {n}" for d, n, w in pl)
            + "\n);"]


def verilog(name, o):
    pl = ports(o)
    if o["builtin"]:
        return builtin(name, o, pl)
    return fabric(name, o, pl)


def fabric(name, o, pl):
    W, D = o["width"], o["depth"]
    AW = int(math.log2(D))
    names = {n for _, n, _ in pl}
    L = header(name, o, pl)
    style = "block" if o["ram"] == "block" else "distributed"
    wclk, rclk = ("clk", "clk") if o["common"] else ("wr_clk", "rd_clk")
    L += [f"    (* ram_style = \"{style}\" *) reg [{W - 1}:0] mem [0:{D - 1}];"]
    if o["common"]:
        L += sync_core(o, AW, names)
    else:
        L += async_core(o, AW, names)
    L.append("endmodule\n")
    return "\n".join(L)


def sync_core(o, AW, names):
    """Common clock. Standard: flags and counts registered from the next state; dout registered on a read.
    FWFT: one output register in front of the memory read (capacity depth + 1)."""
    W, D = o["width"], o["depth"]
    L = [f"    reg [{AW - 1}:0] wp = 0, rp = 0;", f"    reg [{AW}:0] cnt = 0;",
         "    reg full_q = 1'b0, empty_q = 1'b1;",
         f"    reg [{W - 1}:0] dout_q = {W}'d0;",
         "    wire we = wr_en & ~full_q;"]
    if not o["fwft"]:
        L += ["    wire re = rd_en & ~empty_q;",
              f"    wire [{AW}:0] cnt_n = cnt + we - re;",
              f"    always @(posedge clk) if (we) mem[wp] <= din;",
              "    always @(posedge clk) if (re) dout_q <= mem[rp];",
              "    always @(posedge clk) begin",
              "        if (srst) begin wp <= 0; rp <= 0; cnt <= 0; full_q <= 1'b0; empty_q <= 1'b1; end",
              "        else begin",
              "            if (we) wp <= wp + 1'b1;",
              "            if (re) rp <= rp + 1'b1;",
              "            cnt <= cnt_n;",
              f"            full_q <= cnt_n == {D};",
              "            empty_q <= cnt_n == 0;",
              "        end",
              "    end",
              "    assign dout = dout_q;", "    assign full = full_q;", "    assign empty = empty_q;"]
        occ_n, occ = "cnt_n", "cnt"
        rd_ok = "re"
    else:
        L += ["    reg ov = 1'b0;",
              "    wire ie = cnt == 0;",
              "    wire pop = rd_en & ov;",
              "    wire ird = ~ie & (~ov | pop);",
              f"    wire [{AW}:0] cnt_n = cnt + we - ird;",
              "    wire ov_n = ird | (ov & ~pop);",
              f"    wire [{AW + 1}:0] occ_n = cnt_n + ov_n;",
              f"    wire [{AW + 1}:0] occ = cnt + ov;",
              "    always @(posedge clk) if (we) mem[wp] <= din;",
              "    always @(posedge clk) if (ird) dout_q <= mem[rp];",
              "    always @(posedge clk) begin",
              "        if (srst) begin wp <= 0; rp <= 0; cnt <= 0; ov <= 1'b0; full_q <= 1'b0; end",
              "        else begin",
              "            if (we) wp <= wp + 1'b1;",
              "            if (ird) rp <= rp + 1'b1;",
              "            cnt <= cnt_n;",
              "            ov <= ov_n;",
              f"            full_q <= cnt_n == {D};",
              "        end",
              "    end",
              "    assign dout = dout_q;", "    assign full = full_q;", "    assign empty = ~ov;"]
        occ_n, occ = "occ_n", "occ"
        rd_ok = "pop"
    L += flags_sync(o, occ_n, rd_ok, names)
    return L


def flags_sync(o, occ_n, rd_ok, names):
    D = o["depth"]
    L = []
    regs = []
    if "almost_full" in names:
        regs.append(("almost_full", f"{occ_n} >= {D - 1}", "1'b0"))
    if "almost_empty" in names:
        regs.append(("almost_empty", f"{occ_n} <= 1", "1'b1"))
    if "prog_full" in names:
        regs.append(("prog_full", f"{occ_n} >= {o['prog_full']}", "1'b0"))
    if "prog_empty" in names:
        regs.append(("prog_empty", f"{occ_n} <= {o['prog_empty']}", "1'b1"))
    if "data_count" in names:
        regs.append(("data_count", f"{occ_n}[{o['data_count_width'] - 1}:0]", "0"))
    for n, e, r in regs:
        w = o["data_count_width"] if n == "data_count" else 1
        L += [f"    reg {'' if w == 1 else f'[{w - 1}:0] '}{n}_q = {r};",
              f"    always @(posedge clk) {n}_q <= srst ? {r} : {e};", f"    assign {n} = {n}_q;"]
    for n, e in (("valid", rd_ok if not o["fwft"] else None), ("overflow", "wr_en & full_q"),
                 ("underflow", "rd_en & empty_q" if not o["fwft"] else "rd_en & ~ov")):
        if n not in names:
            continue
        if n == "valid" and o["fwft"]:
            L.append("    assign valid = ov;")
            continue
        L += [f"    reg {n}_q = 1'b0;", f"    always @(posedge clk) {n}_q <= srst ? 1'b0 : {e};", f"    assign {n} = {n}_q;"]
    return L


def async_core(o, AW, names):
    """Independent clocks: binary + Gray pointers, CONFIG sync_stages flip-flops each way, flags from the
    synchronized Gray pointer of the other side. FWFT adds one output register on the read side."""
    W, D, S = o["width"], o["depth"], CONFIG["sync_stages"]
    L = [f"    function [{AW}:0] g2b(input [{AW}:0] g); integer i; begin g2b[{AW}] = g[{AW}];",
         f"        for (i = {AW - 1}; i >= 0; i = i - 1) g2b[i] = g2b[i + 1] ^ g[i]; end endfunction",
         "    // reset: rst is synchronized into each domain",
         "    (* ASYNC_REG = \"TRUE\" *) reg [1:0] wrs = 2'b11, rrs = 2'b11;",
         "    always @(posedge wr_clk or posedge rst) if (rst) wrs <= 2'b11; else wrs <= {wrs[0], 1'b0};",
         "    always @(posedge rd_clk or posedge rst) if (rst) rrs <= 2'b11; else rrs <= {rrs[0], 1'b0};",
         "    wire wrst = wrs[1], rrst = rrs[1];",
         "    assign wr_rst_busy = wrst;", "    assign rd_rst_busy = rrst;",
         f"    reg [{AW}:0] wb = 0, wg = 0, rb = 0, rg = 0;",
         f"    (* ASYNC_REG = \"TRUE\" *) reg [{AW}:0] rg_w [0:{S - 1}];",
         f"    (* ASYNC_REG = \"TRUE\" *) reg [{AW}:0] wg_r [0:{S - 1}];",
         "    integer k;", f"    initial for (k = 0; k < {S}; k = k + 1) begin rg_w[k] = 0; wg_r[k] = 0; end",
         f"    always @(posedge wr_clk) begin rg_w[0] <= wrst ? 0 : rg;" +
         "".join(f" rg_w[{i}] <= wrst ? 0 : rg_w[{i - 1}];" for i in range(1, S)) + " end",
         f"    always @(posedge rd_clk) begin wg_r[0] <= rrst ? 0 : wg;" +
         "".join(f" wg_r[{i}] <= rrst ? 0 : wg_r[{i - 1}];" for i in range(1, S)) + " end",
         f"    wire [{AW}:0] rb_w = g2b(rg_w[{S - 1}]);", f"    wire [{AW}:0] wb_r = g2b(wg_r[{S - 1}]);",
         "    reg full_q = 1'b1, empty_q = 1'b1;",
         "    wire we = wr_en & ~full_q;",
         f"    wire [{AW}:0] wb_n = wb + we;",
         f"    wire [{AW}:0] wocc_n = wb_n - rb_w;",
         "    always @(posedge wr_clk) if (we) mem[wb[" + str(AW - 1) + ":0]] <= din;",
         "    always @(posedge wr_clk) begin",
         "        if (wrst) begin wb <= 0; wg <= 0; full_q <= 1'b1; end",
         f"        else begin wb <= wb_n; wg <= wb_n ^ (wb_n >> 1); full_q <= wocc_n == {D}; end",
         "    end",
         "    assign full = full_q;",
         f"    reg [{W - 1}:0] dout_q = {W}'d0;"]
    if not o["fwft"]:
        L += ["    wire re = rd_en & ~empty_q;",
              f"    wire [{AW}:0] rb_n = rb + re;",
              f"    wire [{AW}:0] rocc_n = wb_r - rb_n;",
              f"    always @(posedge rd_clk) if (re) dout_q <= mem[rb[{AW - 1}:0]];",
              "    always @(posedge rd_clk) begin",
              "        if (rrst) begin rb <= 0; rg <= 0; empty_q <= 1'b1; end",
              "        else begin rb <= rb_n; rg <= rb_n ^ (rb_n >> 1); empty_q <= rocc_n == 0; end",
              "    end",
              "    assign empty = empty_q;"]
        rocc, rd_ok, uf = "rocc_n", "re", "rd_en & empty_q"
    else:
        L += ["    reg ov = 1'b0;",
              "    wire ie = wb_r == rb;",
              "    wire pop = rd_en & ov;",
              "    wire ird = ~ie & (~ov | pop);",
              f"    wire [{AW}:0] rb_n = rb + ird;",
              "    wire ov_n = ird | (ov & ~pop);",
              f"    wire [{AW + 1}:0] rocc_n = (wb_r - rb_n) + ov_n;",
              f"    always @(posedge rd_clk) if (ird) dout_q <= mem[rb[{AW - 1}:0]];",
              "    always @(posedge rd_clk) begin",
              "        if (rrst) begin rb <= 0; rg <= 0; ov <= 1'b0; end",
              "        else begin rb <= rb_n; rg <= rb_n ^ (rb_n >> 1); ov <= ov_n; end",
              "    end",
              "    assign empty = ~ov;"]
        rocc, rd_ok, uf = "rocc_n", "pop", "rd_en & ~ov"
    L.append("    assign dout = dout_q;")
    regs = []
    if "almost_full" in names:
        regs.append(("wr_clk", "wrst", "almost_full", f"wocc_n >= {D - 1}", "1'b1", 1))
    if "prog_full" in names:
        regs.append(("wr_clk", "wrst", "prog_full", f"wocc_n >= {o['prog_full']}", "1'b1", 1))
    if "wr_data_count" in names:
        w = o["wr_data_count_width"]
        regs.append(("wr_clk", "wrst", "wr_data_count", f"wocc_n[{AW}:{AW + 1 - w}]", "0", w))
    if "almost_empty" in names:
        regs.append(("rd_clk", "rrst", "almost_empty", f"{rocc} <= 1", "1'b1", 1))
    if "prog_empty" in names:
        regs.append(("rd_clk", "rrst", "prog_empty", f"{rocc} <= {o['prog_empty']}", "1'b1", 1))
    if "rd_data_count" in names:
        w = o["rd_data_count_width"]
        regs.append(("rd_clk", "rrst", "rd_data_count", f"{rocc}[{AW}:{AW + 1 - w}]", "0", w))
    for ck, rs, n, e, r, w in regs:
        L += [f"    reg {'' if w == 1 else f'[{w - 1}:0] '}{n}_q = {r};",
              f"    always @(posedge {ck}) {n}_q <= {rs} ? {r} : {e};", f"    assign {n} = {n}_q;"]
    for ck, rs, n, e in (("rd_clk", "rrst", "valid", rd_ok), ("wr_clk", "wrst", "overflow", "wr_en & full_q"),
                         ("rd_clk", "rrst", "underflow", uf)):
        if n not in names:
            continue
        if n == "valid" and o["fwft"]:
            L.append("    assign valid = ov;")
            continue
        L += [f"    reg {n}_q = 1'b0;", f"    always @(posedge {ck}) {n}_q <= {rs} ? 1'b0 : {e};", f"    assign {n} = {n}_q;"]
    return L


def builtin_shape(o):
    W, D = o["width"], o["depth"]
    for prim, table in (("FIFO18E1", CONFIG["fifo18"]), ("FIFO36E1", CONFIG["fifo36"])):
        for dw, dd in table:
            if W <= dw and D <= dd:
                return prim, dw, dd
    raise FifoError(f"{W}x{D}: no single FIFO18E1/FIFO36E1 shape (cascading is not supported)")


def builtin(name, o, pl):
    prim, dw, dd = builtin_shape(o)
    W = o["width"]
    names = {n for _, n, _ in pl}
    is36 = prim == "FIFO36E1"
    dbus, pbus = (64, 8) if is36 else (32, 4)
    D, P = (dw, 0) if dw < 9 else (dw * 8 // 9, dw // 9)
    L = header(name, o, pl)
    wclk, rclk, rst = ("clk", "clk", "srst") if o["common"] else ("wr_clk", "rd_clk", "rst")
    L += ["    reg [7:0] rcnt = 8'hff;",
          f"    always @(posedge {wclk}) rcnt <= {rst} ? 8'd0 : (rcnt == 8'hff ? rcnt : rcnt + 1'b1);",
          "    wire prst = rcnt < 8'd8;",
          "    wire busy = rcnt < 8'd16;",
          "    reg [7:0] rcnt_r = 8'hff;",
          f"    always @(posedge {rclk}) rcnt_r <= {rst} ? 8'd0 : (rcnt_r == 8'hff ? rcnt_r : rcnt_r + 1'b1);",
          "    wire busy_r = rcnt_r < 8'd16;"]
    if "wr_rst_busy" in names:
        L += ["    assign wr_rst_busy = busy;", "    assign rd_rst_busy = busy_r;"]
    din_d = f"{{{dbus - min(W, D)}'d0, din[{min(W, D) - 1}:0]}}" if dbus > min(W, D) else f"din[{dbus - 1}:0]"
    din_p = f"{{{pbus - (W - D)}'d0, din[{W - 1}:{D}]}}" if W > D else f"{pbus}'d0"
    L += [f"    wire [{dbus - 1}:0] do_d;", f"    wire [{pbus - 1}:0] do_p;", "    wire f_full, f_empty, f_af, f_ae;"]
    af_off = (dd - o["prog_full"]) if o["prog_full"] is not None else 128
    ae_off = o["prog_empty"] if o["prog_empty"] is not None else 128
    mode = ("FIFO36_72" if is36 else "FIFO18_36") if dw in (72, 36) and dd == (512 if is36 else 512) and \
        ((is36 and dw == 72) or (not is36 and dw == 36)) else ("FIFO36" if is36 else "FIFO18")
    en_syn = o["common"] and not o["fwft"]
    prm = [f".DATA_WIDTH({dw})", f'.FIFO_MODE("{mode}")', f'.EN_SYN("{"TRUE" if en_syn else "FALSE"}")',
           f".DO_REG({0 if en_syn else 1})", f'.FIRST_WORD_FALL_THROUGH("{"TRUE" if o["fwft"] else "FALSE"}")',
           f".ALMOST_FULL_OFFSET({13 if is36 else 13}'h{af_off:x})",
           f".ALMOST_EMPTY_OFFSET({13 if is36 else 13}'h{ae_off:x})"]
    conns = [f".WRCLK({wclk})", f".RDCLK({rclk})", ".RST(prst)", ".RSTREG(1'b0)", ".REGCE(1'b1)",
             ".WREN(wr_en & ~busy)", ".RDEN(rd_en & ~busy_r)", f".DI({din_d})", f".DIP({din_p})", ".DO(do_d)",
             ".DOP(do_p)", ".FULL(f_full)", ".EMPTY(f_empty)", ".ALMOSTFULL(f_af)", ".ALMOSTEMPTY(f_ae)",
             ".RDCOUNT()", ".WRCOUNT()", ".RDERR()", ".WRERR()"]
    if is36:
        conns += [".INJECTDBITERR(1'b0)", ".INJECTSBITERR(1'b0)", ".DBITERR()", ".SBITERR()", ".ECCPARITY()"]
    L.append(f"    {prim} #(\n        " + ",\n        ".join(prm) + f"\n    ) u_fifo (\n        " +
             ",\n        ".join(conns) + "\n    );")
    L.append(f"    assign dout = {{" + (f"do_p[{W - D - 1}:0], " if W > D else "") + f"do_d[{min(W, D) - 1}:0]}};")
    L += ["    assign full = f_full | busy;", "    assign empty = f_empty;"]
    if "prog_full" in names:
        L.append("    assign prog_full = f_af;")
    if "prog_empty" in names:
        L.append("    assign prog_empty = f_ae;")
    L.append("endmodule\n")
    return "\n".join(L)


def summary(name, o):
    kind = "builtin " + "/".join(str(x) for x in builtin_shape(o)) if o["builtin"] else f"{o['ram']} RAM"
    return (f"{name}: {o['impl']} {'FWFT' if o['fwft'] else 'standard'} {o['width']}x{o['depth']} ({kind}); ports "
            + ", ".join(n for _, n, _ in ports(o)))
