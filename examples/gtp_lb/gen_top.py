def inst_params(text, prim):
    m = re.search(r"\b%s\s*#\s*\(" % prim, text)
    if not m:
        raise SystemExit(f"no {prim} instance")
    depth, i = 1, m.end()
    while depth:
        depth += {"(": 1, ")": -1}.get(text[i], 0)
        i += 1
    body = re.sub(r"//[^\n]*", "", text[m.end():i - 1])
    out = {}
    for n, v in re.findall(r"\.(\w+)\s*\(\s*((?:[^()]|\([^()]*\))*?)\s*\)\s*(?:,|$)", body):
        out[n] = v.strip()
    return out


def module_params(text):
    out = {}
    for n, v in re.findall(r"parameter\s+(?:\[[^\]]*\]\s*|integer\s+|real\s+)?(\w+)\s*=\s*([^,;)\n]+)", text):
        out[n] = v.strip()
    return out


def resolve(params, mparams):
    out = {}
    for n, v in params.items():
        seen = 0
        while v in mparams and seen < 5:
            v, seen = mparams[v], seen + 1
        out[n] = v
    return out


def plist(prim, given):
    names = [n for n, _ in gt_params.params(prim)]
    defaults = dict(gt_params.params(prim))
    vals = {n: given.get(n, defaults[n]) for n in names}
    vals.update({k: v for k, v in CONFIG["sim_override"].items() if k in vals})
    return ",\n".join(f"        .{n}({vals[n]})" for n in names), sorted(set(names) - set(given))


